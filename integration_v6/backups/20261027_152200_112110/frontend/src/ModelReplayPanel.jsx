import { useEffect, useState } from "react";
import "./modelReplayPanel.css";

const pct = (p) => Number.isFinite(p) ? `${(100 * p).toFixed(1)}%` : "N/A";

export default function ModelReplayPanel({ enabled, onReplay, backendStatus, replayEnabled }) {
  const [index, setIndex] = useState(0);
  const [forecast, setForecast] = useState(null);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(false);

  useEffect(() => {
    if (!enabled) return;
    const controller = new AbortController();
    setLoading(true);
    setError("");
    onReplay?.(null);
    fetch(`/api/replay/step?index=${index}`, { method: "POST", signal: controller.signal })
      .then(async (r) => {
        if (!r.ok) {
          const details = await r.json().catch(() => ({}));
          throw new Error(details.detail || `Replay HTTP ${r.status}`);
        }
        return r.json();
      })
      .then((data) => { setForecast(data); onReplay?.(data); })
      .catch((e) => { if (e.name !== "AbortError") { setError(e.message); setForecast(null); onReplay?.(null); } })
      .finally(() => { if (!controller.signal.aborted) setLoading(false); });
    return () => controller.abort();
  }, [index, enabled]);

  const family = forecast?.family_eta;
  const horizons = forecast?.forecast;
  const matchIndex = forecast?.index === index;
  const canDisplay = enabled && !!forecast && matchIndex;
  const displayFamily = family?.family_if_onset?.replaceAll("_", " / ") ?? "Unavailable";

  return (
    <section className="model-replay-panel" aria-label="NetGuard frozen model predictions">
      <div className="model-panel-top">
        <div>
          <span className="model-panel-kicker">TRAINED MODELS · SYNTHETIC VALIDATION REPLAY</span>
          <h3>Actual model predictions</h3>
          <p>Predictions are generated by the frozen checkpoints, not from mockData.jsx.</p>
        </div>
        <span className={`model-panel-status ${backendStatus === "connected" ? "ok" : ""}`}>
          {backendStatus === "connected" ? "BACKEND CONNECTED" : backendStatus === "checking" ? "CHECKING BACKEND" : "BACKEND DISCONNECTED"}
        </span>
      </div>
      {error && <p className="model-panel-error" role="alert">{error}</p>}
      {!replayEnabled && <p className="model-panel-note">Replay is OFF in Settings. No forecast requests are being sent.</p>}
      {replayEnabled && backendStatus !== "connected" && <p className="model-panel-note">Backend unavailable. Start FastAPI to run replay inferences.</p>}
      {loading && <p className="model-panel-note">Running model inference…</p>}
      {canDisplay && (
        <>
          <div className="model-panel-horizons">
            {[['5 minutes', horizons.h5], ['10 minutes', horizons.h10], ['15 minutes', horizons.h15]].map(([label, prob]) => (
              <div className="model-panel-metric" key={label}>
                <span>Onset within {label}</span><strong>{pct(prob)}</strong>
                <small>Stacked LSTM · synthetic-data prediction</small>
              </div>
            ))}
          </div>
          <div className="model-panel-details">
            <div>
              <span>Most likely family, <em>conditional on attack onset</em></span>
              <strong>{displayFamily}</strong>
              <small>{pct(family.family_probability_if_onset)} conditional family probability · competing-risk LSTM</small>
            </div>
            <div>
              <span>Estimated onset time, <em>conditional on onset within 15 min</em></span>
              <strong>{family.conditional_eta_minutes == null ? "N/A" : `~${family.conditional_eta_minutes.toFixed(1)} min`}</strong>
              <small>Statistical estimate, not a countdown or a guarantee</small>
            </div>
          </div>
          <p className="model-panel-note">Recorded inference #{forecast.history?.id} · Episode {forecast.episode_id} · minute {forecast.episode_minute} · window {forecast.index + 1} of {forecast.total_windows.toLocaleString()} · {forecast.model_release}</p>
        </>
      )}
      <div className="model-panel-controls">
        <button disabled={!enabled || loading || index === 0} onClick={() => setIndex(i => Math.max(0, i - 1))}>Previous window</button>
        <button disabled={!enabled || loading || index >= 18838} onClick={() => setIndex(i => Math.min(18838, i + 1))}>Next window</button>
        <button disabled={!enabled || loading} onClick={() => setIndex(i => (i + 1039) % 18839)}>Jump ahead</button>
        <span>Replay index: {index}</span>
      </div>
      <p className="model-panel-footnote">Replay requests are logged in local SQLite history. No live network feed is connected. The current-attack detector has a separate <code>/api/detect</code> endpoint and requires real 42-feature flow records. Operational alert thresholds are not approved.</p>
    </section>
  );
}
